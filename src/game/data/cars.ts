function toSpec(r: Raw): CarSpec {
  return {
    id: r.id,
    name: r.name,
    tier: r.tier,
    character: r.character,
    length: r.length,
    width: r.width,
    height: r.height,
    wheelbase: r.wheelbase,
    trackWidth: r.trackWidth,
    wheelRadius: r.wheelRadius,
    wheelWidth: r.wheelWidth,
    mass: r.mass,
    peakTorque: r.peakTorque,
    curve: solveTorqueCurve(r.redline, r.peakFrac),
    drive: r.drive,
    frontSplit: r.frontSplit,
    dragArea: r.dragArea,
    downforce: r.downforce,
    price: r.price,
    paint: r.paint,
    sections: makeSections({
      length: r.length,
      width: r.width,
      height: r.height,
      boxiness: r.boxiness,
      notchback: r.notchback,
      cabForward: r.cabForward,
      wheelbase: r.wheelbase,
    } as never),
    wing: r.wing,
    splitter: r.splitter,
    rideHeight: r.rideHeight,
  };
}

export const CARS: CarSpec[] = RAW.map(toSpec);
export const CAR_BY_ID: Record<string, CarSpec> = Object.fromEntries(
  CARS.map((c) => [c.id, c]),
);
